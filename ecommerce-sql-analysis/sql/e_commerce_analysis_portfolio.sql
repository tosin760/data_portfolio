            WHEN days_since_purchase <= 600 THEN 'Active'
            WHEN days_since_purchase <= 700 THEN 'At Risk'
            ELSE 'Churned'
        END AS customer_status
    FROM customer_recency
)
SELECT
    c.customer_segment,
    COUNT(*) AS total_purchasing_customers,
    SUM(CASE WHEN cs.customer_status = 'Churned' THEN 1 ELSE 0 END) AS churned_customers,
    ROUND(SUM(CASE WHEN cs.customer_status = 'Churned' THEN 1 ELSE 0 END) * 100 / COUNT(*), 2) AS churn_rate
FROM customer_status cs
JOIN customers c
    ON cs.customer_id = c.customer_id
GROUP BY c.customer_segment
ORDER BY churn_rate;

-- Are high-revenue customers more likely to churn than low-revenue ones?

WITH customer_revenue AS (
    SELECT
        o.customer_id,
        ROUND(SUM(oi.quantity * p.unit_price), 2) AS total_revenue
    FROM orders o
    JOIN order_items oi
        ON o.order_id = oi.order_id
    JOIN products p
        ON oi.product_id = p.product_id
    WHERE o.order_status = 'Completed'
    GROUP BY o.customer_id
),
last_purchase AS (
    SELECT
        customer_id,
        MAX(order_date) AS last_order_date
    FROM orders
    WHERE order_status = 'Completed'
    GROUP BY customer_id
),
customer_status AS (
    SELECT
        cr.customer_id,
        cr.total_revenue,
        lp.last_order_date,
        DATEDIFF('2025-12-31', lp.last_order_date) AS days_since_purchase,
        CASE
            WHEN DATEDIFF('2025-12-31', lp.last_order_date) <= 600 THEN 'Active'
            WHEN DATEDIFF('2025-12-31', lp.last_order_date) <= 700 THEN 'At Risk'
            ELSE 'Churned'
        END AS customer_status
    FROM customer_revenue cr
    JOIN last_purchase lp
        ON cr.customer_id = lp.customer_id
),
revenue_groups AS (
    SELECT
        *,
        NTILE(4) OVER (ORDER BY total_revenue DESC) AS revenue_quartile
    FROM customer_status
)
SELECT
    revenue_quartile,
    COUNT(*) AS customers,
    SUM(CASE WHEN customer_status = 'Churned' THEN 1 ELSE 0 END) AS churned_customers,
    ROUND(SUM(CASE WHEN customer_status = 'Churned' THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS churn_rate
FROM revenue_groups
GROUP BY revenue_quartile
ORDER BY revenue_quartile;